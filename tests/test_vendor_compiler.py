from pathlib import Path

import yaml

from ghosla.core.vendor import compile_sources, load_source_manifest


def test_load_source_manifest(tmp_path: Path) -> None:
    manifest_file = tmp_path / "test-source.yml"
    manifest_file.write_text(
        """name: test-repo
git:
  url: https://github.com/example/repo
  ref: main
newRootPath: sub/dir
extraExcludePaths:
  - "custom/**"
""",
        encoding="utf-8",
    )
    source = load_source_manifest(manifest_file)
    assert source.name == "test-repo"
    assert source.git["url"] == "https://github.com/example/repo"
    assert source.newRootPath == "sub/dir"
    assert "custom/**" in source.extraExcludePaths


def test_compile_sources(tmp_path: Path) -> None:
    sources_d = tmp_path / "sources.d"
    sources_d.mkdir()

    defaults_file = sources_d / "_defaults.yml"
    defaults_file.write_text(
        """apiVersion: ghosla.io/v1alpha1
kind: UpstreamDefaults
excludePaths:
  - ".git/**"
  - ".github/**"
""",
        encoding="utf-8",
    )

    source1 = sources_d / "repo-one.yml"
    source1.write_text(
        """name: repo-one
git:
  url: https://github.com/example/one
  ref: main
extraExcludePaths:
  - "tests/**"
""",
        encoding="utf-8",
    )

    source2 = sources_d / "repo-two.yml"
    source2.write_text(
        """name: repo-two
git:
  url: https://github.com/example/two
  ref: main
newRootPath: plugin
""",
        encoding="utf-8",
    )

    output_vendir = tmp_path / "vendir.yml"
    compile_sources(sources_d, output_vendir)

    assert output_vendir.exists()
    content = output_vendir.read_text(encoding="utf-8")
    assert "Generated by Ghosla - DO NOT EDIT DIRECTLY" in content

    parsed = yaml.safe_load(content)
    assert parsed["apiVersion"] == "vendir.k14s.io/v1alpha1"
    assert parsed["kind"] == "Config"
    assert len(parsed["directories"]) == 2

    dir_map = {d["path"]: d for d in parsed["directories"]}
    assert "upstream/repo-one" in dir_map
    contents1 = dir_map["upstream/repo-one"]["contents"][0]
    assert contents1["git"]["url"] == "https://github.com/example/one"
    # Should include default excludes + extra excludes
    assert ".git/**" in contents1["excludePaths"]
    assert "tests/**" in contents1["excludePaths"]

    assert "upstream/repo-two" in dir_map
    contents2 = dir_map["upstream/repo-two"]["contents"][0]
    assert contents2["newRootPath"] == "plugin"
    assert ".git/**" in contents2["excludePaths"]
    assert "tests/**" not in contents2["excludePaths"]
