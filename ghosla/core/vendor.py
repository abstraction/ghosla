import subprocess
from pathlib import Path
from typing import Any, Dict, List, Tuple

import yaml

from ghosla.core.models import UpstreamDefaults, UpstreamSource


def load_defaults(defaults_file: Path) -> UpstreamDefaults:
    """Loads shared defaults from _defaults.yml."""
    if not defaults_file.exists():
        return UpstreamDefaults()

    with open(defaults_file, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    if not isinstance(data, dict):
        return UpstreamDefaults()
    return UpstreamDefaults(**data)


def load_source_manifest(manifest_file: Path) -> UpstreamSource:
    """Loads a single upstream source manifest."""
    with open(manifest_file, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    if not isinstance(data, dict):
        raise ValueError(f"Invalid YAML in {manifest_file}")
    return UpstreamSource(**data)


def compile_sources(sources_dir: Path, output_file: Path) -> Dict[str, Any]:
    """Compiles sources.d manifests into vendir.yml."""
    defaults_file = sources_dir / "_defaults.yml"
    defaults = load_defaults(defaults_file)

    manifest_files = sorted(
        [
            p for p in sources_dir.iterdir()
            if p.suffix in (".yml", ".yaml") and not p.name.startswith("_")
        ],
        key=lambda p: p.name,
    )

    directories: List[Dict[str, Any]] = []
    for mf in manifest_files:
        src = load_source_manifest(mf)

        # Merge excludePaths preserving order and uniqueness
        combined_excludes: List[str] = list(defaults.excludePaths)
        for extra in src.extraExcludePaths:
            if extra not in combined_excludes:
                combined_excludes.append(extra)

        content_entry: Dict[str, Any] = {
            "path": ".",
            "git": {
                "url": src.git["url"],
                "ref": src.git.get("ref", "main"),
            },
        }
        if src.newRootPath:
            content_entry["newRootPath"] = src.newRootPath

        content_entry["excludePaths"] = combined_excludes

        directories.append({
            "path": f"upstream/{src.name}",
            "contents": [content_entry],
        })

    vendir_cfg: Dict[str, Any] = {
        "apiVersion": "vendir.k14s.io/v1alpha1",
        "kind": "Config",
        "directories": directories,
    }

    yaml_str = yaml.safe_dump(vendir_cfg, sort_keys=False, default_flow_style=False)
    header = "# Generated by Ghosla - DO NOT EDIT DIRECTLY\n"
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(header + yaml_str, encoding="utf-8")

    return vendir_cfg


def run_vendir_sync(
    workspace_root: Path,
    vendir_bin: str = "vendir",
) -> Tuple[int, str, str]:
    """Compiles vendir.yml and runs vendir sync."""
    sources_d = workspace_root / "sources.d"
    output_vendir = workspace_root / "vendir.yml"
    compile_sources(sources_d, output_vendir)

    proc = subprocess.run(
        [vendir_bin, "sync"],
        cwd=workspace_root,
        capture_output=True,
        text=True,
    )
    return proc.returncode, proc.stdout, proc.stderr
